"""RAG vs. no-RAG comparison for the paper.

For the first N benchmark questions this script:

* takes the RAG answer from an existing ``results/answer_eval.json`` (already
  generated by ``chirag eval --answer N --judge``), and
* generates a no-RAG baseline answer with the SAME local model but NO
  retrieved context (only a generic assistant system prompt), and
* scores BOTH answers with an independent judge model against the
  concatenated GOLD source text (the documents the benchmark says should
  support each question).

Output: ``results/rag_vs_no_rag.json`` with per-question rows and a printed
summary of mean faithfulness, citation presence rates and judge sample size.

Usage::

    python -m chirag.eval_no_rag --limit 15
"""

from __future__ import annotations

import argparse
import json
import statistics
from typing import Any, Dict, List

from .config import get_settings, PROJECT_ROOT
from .embeddings import build_embedding_provider
from .evaluation import JUDGE_SYSTEM, JUDGE_USER, load_benchmark, judge_faithfulness
from .llm import OllamaLLM
from .vector_store import VectorStore

NO_RAG_SYSTEM = (
    "You are a knowledgeable assistant in cryptography and cryptanalysis. "
    "Answer the user's question directly from your knowledge. If you are not "
    "sure about a specific number or parameter, state your uncertainty."
)


def gold_text_for(store: VectorStore, gold_sources: List[str]) -> str:
    """Concatenate the text of the documents that benchmark gold labels
    refer to (substring match against document sources, like the eval)."""
    docs = store.list_documents()
    parts: List[str] = []
    seen = set()
    for doc in docs:
        if any(g.lower() in doc["source"].lower() for g in gold_sources):
            if doc["source"] in seen:
                continue
            seen.add(doc["source"])
            text = store.get_document_text(doc["source"], max_chunks=25)
            if text.strip():
                parts.append(f"--- {doc['source']} ---\n{text}")
    return "\n\n".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser(description="RAG vs no-RAG comparison")
    ap.add_argument("--limit", type=int, default=15)
    ap.add_argument("--answers", default=str(PROJECT_ROOT / "results"
                                             / "answer_eval.json"))
    ap.add_argument("--benchmark", default=str(PROJECT_ROOT / "eval"
                                               / "qa_benchmark.json"))
    ap.add_argument("--gen-model", default="qwen3.5:9b")
    ap.add_argument("--judge-model", default="gemma4:26b")
    args = ap.parse_args()

    settings = get_settings()
    provider = build_embedding_provider(settings)
    store = VectorStore(settings, provider)
    gen = OllamaLLM(args.gen_model, settings.ollama_base_url)
    judge = OllamaLLM(args.judge_model, settings.ollama_base_url)

    items = load_benchmark(args.benchmark)[:args.limit]
    with open(args.answers, "r", encoding="utf-8") as f:
        rag_log = json.load(f)
    rag_by_q = {e["question"]: e for e in rag_log}

    rows: List[Dict[str, Any]] = []
    for i, item in enumerate(items, 1):
        gold = gold_text_for(store, item.gold_sources)
        rag = rag_by_q.get(item.question, {})
        rag_answer = (rag.get("answer") or "").strip()

        norag_answer = ""
        for _attempt in range(3):
            try:
                norag_answer = gen.generate(
                    item.question, system_prompt=NO_RAG_SYSTEM,
                    temperature=0.2,
                    max_tokens=settings.max_gen_tokens).strip()
            except Exception as exc:
                print(f"[no-rag] {i} generation error: {exc}", flush=True)
                continue
            if norag_answer:
                break
            print(f"[no-rag] {i} empty answer, retry", flush=True)

        print(f"[no-rag] {i}/{len(items)} generating judge calls…", flush=True)
        rag_faith = judge_faithfulness(judge, item, gold, rag_answer) \
            if rag_answer else 0
        norag_faith = judge_faithfulness(judge, item, gold, norag_answer) \
            if norag_answer else 0

        rows.append({
            "question": item.question,
            "category": item.category,
            "gold_sources": item.gold_sources,
            "gold_text_length": len(gold),
            "rag_answer": rag_answer,
            "norag_answer": norag_answer,
            "rag_faithfulness": rag_faith,
            "norag_faithfulness": norag_faith,
            "rag_citation_rate": rag.get("citation_rate", 0.0),
            "norag_has_citation": "SOURCE" in norag_answer,
        })

    out_path = PROJECT_ROOT / "results" / "rag_vs_no_rag.json"
    out_path.write_text(json.dumps(rows, indent=2, ensure_ascii=False),
                        encoding="utf-8")

    rag_s = [r["rag_faithfulness"] for r in rows if r["rag_faithfulness"]]
    nr_s = [r["norag_faithfulness"] for r in rows if r["norag_faithfulness"]]
    rag_cite = sum(1 for r in rows if r["rag_citation_rate"] > 0)
    nr_cite = sum(1 for r in rows if r["norag_has_citation"])
    print("\n=== RAG vs no-RAG ===")
    print(f"questions: {len(rows)}")
    print(f"RAG    faithfulness mean={statistics.mean(rag_s):.2f}/5 (n={len(rag_s)})  "
          f"answers with citations: {rag_cite}/{len(rows)}")
    print(f"no-RAG faithfulness mean={statistics.mean(nr_s):.2f}/5 (n={len(nr_s)})  "
          f"answers with citations: {nr_cite}/{len(rows)}")


if __name__ == "__main__":
    main()
